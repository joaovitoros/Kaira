package com.JCODE.domain;

public class FrameSlot {

    private String frame;
    private String slot;

    public FrameSlot(String frame, String slot) {
        this.frame = frame;
        this.slot = slot;
    }

    public String getFrame() {
        return frame;
    }

    public String getSlot() {
        return slot;
    }
}